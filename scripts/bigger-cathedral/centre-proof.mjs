import fs from 'node:fs';
import {render} from './render.mjs';
const OUT=process.argv[2]??'/Users/pragadees.xd/Downloads/Ducky Land/concepts/themes/work/bellovo-check/inner';
const read=p=>JSON.parse(fs.readFileSync(p)),art=read('public/pixi-art/themes/cathedral/art.json'),D='assets/world/themes/cathedral/';
fs.mkdirSync(OUT,{recursive:true});
const camera={x:1150,y:450,k:.3,width:1750,height:1350};
fs.writeFileSync(OUT+'/centre.png',await render(art,camera));
const world=read(D+'world.json'),walk=read(D+'walk-world.json'),harbor=read(D+'harbor.json');
fs.writeFileSync(OUT+'/centre-sleepers.png',await render(art,{...camera,world,walk,harbor}));
fs.writeFileSync(OUT+'/overview.png',await render(art,{x:-2200,y:-2400,k:.12,width:1536,height:1248,world,walk,harbor}));
console.log('Wrote centre.png, centre-sleepers.png and overview.png to '+OUT);
