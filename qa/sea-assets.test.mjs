import assert from 'node:assert/strict';
import test from 'node:test';
import {Assets, Container, Texture} from 'pixi.js';
import {createSea} from '../src/pixi/sea-islands.js';

test('island signs share fetched artwork and release generated textures after the final sea closes', async t => {
  const originalFetch = globalThis.fetch, load = Assets.load, unload = Assets.unload;
  const loaded = [], unloaded = [];
  let fetched = 0;
  globalThis.fetch = async () => {fetched++; return {ok: true, text: async () => '<svg><text x="20" font-size="22">LITTLE ISLE</text></svg>'};};
  Assets.load = async ({src}) => {loaded.push(src); return Texture.EMPTY;};
  Assets.unload = async src => {unloaded.push(src);};
  t.after(() => {globalThis.fetch = originalFetch; Assets.load = load; Assets.unload = unload;});
  const objects = new Container(), otherObjects = new Container();
  const sea = await createSea(new Container(), objects), other = await createSea(new Container(), otherObjects);
  const destination = name => ({name, destination: name, land: {x: 0, y: 0}});
  await sea.switchIsland([destination('Test A'), destination('Test B')]);
  await other.switchIsland([destination('Test A')]);
  assert.equal(fetched, 1);
  assert.equal(loaded.length, 2);
  sea.dispose(); sea.dispose();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(objects.children.length, 0);
  assert.deepEqual(unloaded, [loaded[1]]);
  other.dispose();
  await new Promise(resolve => setImmediate(resolve));
  assert.equal(otherObjects.children.length, 0);
  assert.deepEqual(unloaded, [loaded[1], loaded[0]]);
  objects.destroy(); otherObjects.destroy();
});
